//! Inputs and decode workloads shared by the criterion benches and the `ab`
//! comparison example.
//!
//! The workloads are a macro, [`workloads!`], instantiated once per crate
//! they measure: the criterion benches instantiate it against the working
//! tree (the [`candidate`] module here), and `examples/ab.rs` instantiates
//! it against two crates at once - a baseline revision and the candidate -
//! so both run in one binary. The macro uses only API that both sides have.
//! Every workload is `#[inline(never)]`: the unit that is timed, and the
//! intended entry point for reading its assembly. That is a hint, not a
//! guarantee of a separate copy - LLVM's function merging folds
//! instantiations that compile to identical code into one - so whether each
//! survives, and whether its hot loop is its own, has to be checked in the
//! built executable.
//!
//! Every input is generated by the working tree's encoders and is well-formed.
//! See `reference/performance.md` for the method these exist for.

use protohoggr::{
    encode_bytes_field_always, encode_fixed32_field_always, encode_fixed64_field_always,
    encode_packed_sint64, encode_varint_field_always,
};

/// Values per packed input, fields per message input.
pub const N: usize = 8000;

/// Distinct buffers per input set. A workload rotates through them, so it
/// is not replaying one buffer; the eight-buffer cycle itself still repeats.
pub const BUFS: usize = 8;

/// Xorshift64: a fixed, dependency-free stream, so every run and both sides
/// of a comparison see the same inputs.
#[derive(Debug)]
pub struct Rng(u64);

impl Rng {
    /// The seed every input set is drawn from.
    #[must_use]
    pub const fn new() -> Self {
        Self(0x1234_5678_9abc_def0)
    }

    /// The next value of the stream.
    pub fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }

    /// A value in `0..bound`, `bound` small enough that the modulo bias does
    /// not matter here.
    pub fn below(&mut self, bound: u64) -> u64 {
        self.next_u64() % bound
    }
}

impl Default for Rng {
    fn default() -> Self {
        Self::new()
    }
}

/// The packed sint64 body (no tag, no length prefix) holding `values`.
#[must_use]
pub fn packed_sint64_body(values: &[i64]) -> Vec<u8> {
    let mut buf = Vec::new();
    let mut scratch = Vec::new();
    encode_packed_sint64(&mut buf, &mut scratch, 1, values);
    let mut cursor = protohoggr::Cursor::new(&buf);
    match (cursor.read_tag(), cursor.read_len_delimited()) {
        (Ok(Some(_)), Ok(body)) => body.to_vec(),
        _ => unreachable!("encode_packed_sint64 wrote a tag and a length-delimited body"),
    }
}

/// Signed offset of `r` below `bound` around zero: `r % bound - bound / 2`.
fn centered(r: u64, bound: u64) -> i64 {
    i64::try_from(r % bound).unwrap_or(0) - i64::try_from(bound / 2).unwrap_or(0)
}

/// `N` values in `-50..50`: one-byte zigzag varints.
pub fn small_values(rng: &mut Rng) -> Vec<i64> {
    (0..N).map(|_| centered(rng.next_u64(), 100)).collect()
}

/// `N` values in `-500_000..500_000`: mostly three-byte zigzag varints.
pub fn large_values(rng: &mut Rng) -> Vec<i64> {
    (0..N)
        .map(|_| centered(rng.next_u64(), 1_000_000))
        .collect()
}

/// `N` uniformly random `i64`: mostly nine- and ten-byte zigzag varints, in
/// about equal numbers, with a few shorter ones.
pub fn random_values(rng: &mut Rng) -> Vec<i64> {
    (0..N)
        .map(|_| i64::from_ne_bytes(rng.next_u64().to_ne_bytes()))
        .collect()
}

/// `N` values whose zigzag varint is exactly ten bytes, both signs.
///
/// Zigzag maps `v >= 2^62` to `2v >= 2^63` and `v < -2^62` to
/// `-2v - 1 > 2^63`; everything else fits in nine bytes or fewer.
pub fn ten_byte_values(rng: &mut Rng) -> Vec<i64> {
    (0..N)
        .map(|_| {
            let r = rng.next_u64();
            // Bits 62 set and 63 clear: a value in [2^62, 2^63).
            let magnitude = i64::try_from((r >> 2) | (1 << 62)).unwrap_or(i64::MAX);
            if r & 1 == 0 {
                magnitude
            } else {
                -magnitude - 1
            }
        })
        .collect()
}

/// A message of `n` fields cycling through a varint (field 1), five bytes
/// (2), a fixed32 (3), a fixed64 (4, skipped by the workloads) and a wider
/// varint (6, skipped).
pub fn message_mixed(rng: &mut Rng, n: usize) -> Vec<u8> {
    let mut buf = Vec::new();
    for i in 0..n {
        let r = rng.next_u64();
        match i % 5 {
            0 => encode_varint_field_always(&mut buf, 1, r % 300),
            1 => encode_bytes_field_always(&mut buf, 2, &[7u8; 5]),
            2 => encode_fixed32_field_always(&mut buf, 3, low32(r)),
            3 => encode_fixed64_field_always(&mut buf, 4, r),
            _ => encode_varint_field_always(&mut buf, 6, r >> 20),
        }
    }
    buf
}

/// A message of `n` fields, each at random a fixed32 (field 3) or three
/// bytes (2): only fixed-width and short length-delimited reads.
pub fn message_fixed_len(rng: &mut Rng, n: usize) -> Vec<u8> {
    let mut buf = Vec::new();
    for _ in 0..n {
        let r = rng.next_u64();
        if r & 1 == 0 {
            encode_fixed32_field_always(&mut buf, 3, low32(r));
        } else {
            encode_bytes_field_always(&mut buf, 2, &[7u8; 3]);
        }
    }
    buf
}

/// A message of `n` fields, each at random a fixed32 (field 16) or 130
/// bytes (17): two-byte tags and two-byte length prefixes.
pub fn message_wide_tags(rng: &mut Rng, n: usize) -> Vec<u8> {
    let mut buf = Vec::new();
    for _ in 0..n {
        let r = rng.next_u64();
        if r & 1 == 0 {
            encode_fixed32_field_always(&mut buf, 16, low32(r));
        } else {
            encode_bytes_field_always(&mut buf, 17, &[7u8; 130]);
        }
    }
    buf
}

fn low32(r: u64) -> u32 {
    u32::try_from(r & u64::from(u32::MAX)).unwrap_or(0)
}

/// `BUFS` buffers drawn one after another from `rng`.
pub fn rotated(rng: &mut Rng, mut make: impl FnMut(&mut Rng) -> Vec<u8>) -> Vec<Vec<u8>> {
    (0..BUFS).map(|_| make(rng)).collect()
}

/// Every input set, drawn in a fixed order from one [`Rng`].
#[derive(Debug)]
pub struct Inputs {
    /// Packed sint64, one-byte varints.
    pub small: Vec<Vec<u8>>,
    /// Packed sint64, mostly three-byte varints.
    pub large: Vec<Vec<u8>>,
    /// Packed sint64, mostly nine- and ten-byte varints.
    pub random: Vec<Vec<u8>>,
    /// Packed sint64, ten-byte varints only.
    pub ten: Vec<Vec<u8>>,
    /// Tag-dispatch message, mixed field kinds.
    pub mixed: Vec<Vec<u8>>,
    /// Tag-dispatch message, fixed32 and short length-delimited fields.
    pub fixed_len: Vec<Vec<u8>>,
    /// Tag-dispatch message, two-byte tags and lengths.
    pub wide_tags: Vec<Vec<u8>>,
}

impl Inputs {
    /// Generate every set.
    #[must_use]
    pub fn generate() -> Self {
        let mut rng = Rng::new();
        let rng = &mut rng;
        Self {
            small: rotated(rng, |r| packed_sint64_body(&small_values(r))),
            large: rotated(rng, |r| packed_sint64_body(&large_values(r))),
            random: rotated(rng, |r| packed_sint64_body(&random_values(r))),
            ten: rotated(rng, |r| packed_sint64_body(&ten_byte_values(r))),
            mixed: rotated(rng, |r| message_mixed(r, N)),
            fixed_len: rotated(rng, |r| message_fixed_len(r, N)),
            wide_tags: rotated(rng, |r| message_wide_tags(r, N / 2)),
        }
    }

    /// The packed sint64 sets by name.
    #[must_use]
    pub fn packed(&self) -> [(&'static str, &[Vec<u8>]); 4] {
        [
            ("small", &self.small),
            ("large", &self.large),
            ("random", &self.random),
            ("ten_byte", &self.ten),
        ]
    }

    /// The message sets by name.
    #[must_use]
    pub fn messages(&self) -> [(&'static str, &[Vec<u8>]); 3] {
        [
            ("mixed", &self.mixed),
            ("fixed_len", &self.fixed_len),
            ("wide_tags", &self.wide_tags),
        ]
    }
}

/// Instantiate the decode workloads against one crate.
///
/// `workloads!(pub mod name = krate)` defines module `name` holding one
/// `#[inline(never)]` function per workload, each calling `krate`'s API:
///
/// - `msg_question(&[u8]) -> krate::WireResult<u64>`: a tag-dispatch loop
///   that reads fields 1 (varint), 2 and 17 (length-delimited), 3 and 16
///   (fixed32), skips every other field, and propagates errors with `?`.
/// - `msg_unwrap(&[u8]) -> u64`: the same loop with `.unwrap()` on every read.
/// - `packed_sum(&[u8]) -> i64`: `PackedSint64Iter` folded with wrapping
///   addition, so its result is defined for any input in every profile.
/// - `cumulative(&[u8], &mut Vec<i64>)`: `decode_packed_sint64_cumulative`
///   into a cleared vector.
///
/// The crate is named by a path segment visible where the macro is invoked:
/// a dependency name such as `protohoggr` or `protohoggr_base`.
#[macro_export]
macro_rules! workloads {
    ($vis:vis mod $name:ident = $krate:ident) => {
        #[doc = concat!("The decode workloads against `", stringify!($krate), "`.")]
        $vis mod $name {
            use $krate::{Cursor, PackedSint64Iter, WIRE_32BIT, WIRE_LEN, WIRE_VARINT};

            /// Tag-dispatch loop propagating errors with `?`.
            ///
            /// # Errors
            ///
            /// The first read error, on malformed input only.
            #[inline(never)]
            pub fn msg_question(data: &[u8]) -> $krate::WireResult<u64> {
                let mut c = Cursor::new(data);
                let mut acc = 0u64;
                while let Some((field, wire)) = c.read_tag()? {
                    match (field, wire) {
                        (1, WIRE_VARINT) => acc = acc.wrapping_add(c.read_varint()?),
                        (2 | 17, WIRE_LEN) => {
                            acc = acc.wrapping_add(c.read_len_delimited()?.len() as u64);
                        }
                        (3 | 16, WIRE_32BIT) => {
                            acc = acc.wrapping_add(u64::from(c.read_fixed32()?));
                        }
                        _ => c.skip_field(wire)?,
                    }
                }
                Ok(acc)
            }

            /// Tag-dispatch loop unwrapping every read.
            ///
            /// # Panics
            ///
            /// On malformed input only.
            // The unwrap codegen is what this measures. clippy's unwrap_used
            // does not fire inside macro expansions, so it needs no expect.
            #[inline(never)]
            pub fn msg_unwrap(data: &[u8]) -> u64 {
                let mut c = Cursor::new(data);
                let mut acc = 0u64;
                while let Some((field, wire)) = c.read_tag().unwrap() {
                    match (field, wire) {
                        (1, WIRE_VARINT) => acc = acc.wrapping_add(c.read_varint().unwrap()),
                        (2 | 17, WIRE_LEN) => {
                            acc = acc.wrapping_add(c.read_len_delimited().unwrap().len() as u64);
                        }
                        (3 | 16, WIRE_32BIT) => {
                            acc = acc.wrapping_add(u64::from(c.read_fixed32().unwrap()));
                        }
                        _ => c.skip_field(wire).unwrap(),
                    }
                }
                acc
            }

            /// Packed sint64 iterator, wrapping sum.
            #[inline(never)]
            #[must_use]
            pub fn packed_sum(data: &[u8]) -> i64 {
                PackedSint64Iter::new(data).fold(0i64, i64::wrapping_add)
            }

            /// Batch cumulative packed sint64 decode.
            #[inline(never)]
            pub fn cumulative(data: &[u8], out: &mut Vec<i64>) {
                out.clear();
                $krate::decode_packed_sint64_cumulative(data, 0, out);
            }
        }
    };
}

workloads!(pub mod candidate = protohoggr);
